export const ROAST_COUNT = Object.values(ROASTS).reduce((sum, group) => sum + group.length, 0);
const recent = [];
export function getRoast(category = "general", custom = [], amount) {
  const messages = [...(ROASTS[category] || ROASTS.general), ...(Array.isArray(custom) ? custom.filter((x) => typeof x === "string" && x.trim()) : [])];
  const candidates = messages.filter((message) => !recent.includes(message));
  const picked = candidates[Math.floor(Math.random() * candidates.length)] || messages[0];
  recent.push(picked);
  if (recent.length > 8) recent.shift();
  return picked + (typeof amount === "number" ? " Suma înregistrată: " + amount.toLocaleString("ro-RO", { minimumFractionDigits: 2 }) + " lei." : "");
}
